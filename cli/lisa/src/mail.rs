//! `lisa mail` — join a connected account to the Maildir the Mail app reads.
//!
//! Lisa does not speak IMAP and will not (apps/mail/README.md "Sync is
//! somebody else's job"). What was missing was not a mail client, it was
//! the wiring: GNOME Online Accounts holds an OAuth2 token, `mbsync`
//! turns IMAP into a Maildir, and nothing wrote the config that lets
//! them talk. This module is that config, plus the token helper mbsync
//! calls to get a fresh credential each run.
//!
//! # What is deliberately conservative
//!
//! **Nothing here can destroy mail on the server.** `Expunge None` on
//! both sides means a message can be flagged deleted and never actually
//! removed; `Remove None` means a folder that vanishes locally does not
//! take its remote twin with it. The Mail app's own Trash button is a
//! move for the same reason. A first release of a sync path is the worst
//! possible place to find out that a filename bug propagates.
//!
//! **The config is ours, at our own path.** `~/.mbsyncrc` is where a
//! person's hand-written config lives, and writing there would silently
//! replace it. We write `~/.config/lisa/mbsyncrc` and always pass `-c`.

use anyhow::{Context, Result, bail};
use std::path::{Path, PathBuf};

/// A mail account, reduced to what a syncer needs.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Account {
    /// GOA's object id — used to ask for a token later.
    pub id: String,
    pub identity: String,
    pub imap_host: String,
    pub imap_user: String,
    /// `true` for implicit TLS on 993 (`ImapUseSsl`), which is what
    /// Gmail advertises. `false` means STARTTLS on 143.
    pub imap_ssl: bool,
    /// Submission host, when the account reports one. GOA does for
    /// Google (`smtp.gmail.com`); derived from the IMAP host otherwise.
    pub smtp_host: Option<String>,
}

/// How mbsync proves who we are.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Credential {
    /// An OAuth2 token, fetched per run from Online Accounts. Needs the
    /// XOAUTH2 SASL mechanism (os/packages/cyrus-sasl-xoauth2).
    OnlineAccount,
    /// A provider-issued app password, read from a file. Works with
    /// stock isync and with providers that offer nothing else.
    AppPassword { file: PathBuf },
}

/// Where everything lives.
#[derive(Debug, Clone)]
pub struct Paths {
    pub maildir: PathBuf,
    pub config: PathBuf,
    pub send_config: PathBuf,
}

impl Paths {
    pub fn new(home: &Path, maildir: Option<PathBuf>) -> Self {
        Self {
            maildir: maildir.unwrap_or_else(|| home.join("Mail")),
            config: home.join(".config/lisa/mbsyncrc"),
            // Ours, at our own path, for the same reason as mbsyncrc:
            // ~/.msmtprc is where a person's hand-written config lives.
            send_config: home.join(".config/lisa/msmtprc"),
        }
    }
}

/// Written into every generated config so we can tell our file from a
/// hand-written one and refuse to clobber the latter.
pub const MARKER: &str = "# Generated by `lisa mail setup`. Edits are lost on the next run.";

/// Gmail's special folders, mapped to the names the Mail app orders by
/// (apps/mail `FOLDER_ORDER`).
///
/// `[Gmail]/All Mail` is deliberately absent: it contains a copy of
/// every message in every other folder, so syncing it doubles the disk
/// and shows every message twice.
const GMAIL_FOLDERS: &[(&str, &str)] = &[
    ("INBOX", "INBOX"),
    ("[Gmail]/Sent Mail", "Sent"),
    ("[Gmail]/Drafts", "Drafts"),
    ("[Gmail]/Trash", "Trash"),
    ("[Gmail]/Spam", "Spam"),
];

/// Non-Gmail servers: sync the inbox and whatever else exists by name.
const GENERIC_FOLDERS: &[(&str, &str)] = &[
    ("INBOX", "INBOX"),
    ("Sent", "Sent"),
    ("Drafts", "Drafts"),
    ("Trash", "Trash"),
];

fn is_gmail(host: &str) -> bool {
    let host = host.to_ascii_lowercase();
    host == "imap.gmail.com" || host.ends_with(".gmail.com") || host == "imap.googlemail.com"
}

/// Quote a value for mbsync's config grammar.
///
/// Folder names are the reason this exists: `[Gmail]/Sent Mail` has a
/// space in it, and an unquoted space ends the value.
fn quote(value: &str) -> String {
    format!("\"{}\"", value.replace('\\', r"\\").replace('"', "\\\""))
}

/// A name safe to use as a directory and as an mbsync identifier.
///
/// The account's address with the characters that mean something to a
/// path or to mbsync's grammar removed. `you@example.com` becomes
/// `you_at_example.com`, which is still recognisable in a file manager —
/// the Maildir is a directory a person will open one day.
pub fn slug(address: &str) -> String {
    let cleaned: String = address
        .trim()
        .replace('@', "_at_")
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '.' || c == '-' || c == '_' {
                c
            } else {
                '_'
            }
        })
        .collect();
    // `.` and `..` survive the filter above because a dot is legal in
    // an address, and both name a directory OUTSIDE the one we are
    // building a path in. An address is never literally `..`; a
    // function that can emit it is still a path-traversal waiting for
    // the day something else calls it.
    if cleaned.is_empty() || cleaned.chars().all(|c| c == '.') {
        "account".into()
    } else {
        cleaned
    }
}

/// Where one account's mail lives under the Maildir root.
///
/// Each account gets its own subtree. A shared tree would merge two
/// people's inboxes into one folder with no way to tell them apart, and
/// "which account is this from" is the question the sidebar exists to
/// answer.
pub fn account_root(maildir: &Path, address: &str, multi: bool) -> PathBuf {
    if multi {
        maildir.join(slug(address))
    } else {
        maildir.to_path_buf()
    }
}

/// The whole config file, as text.
///
/// Pure on purpose — this is the part that is easy to get subtly wrong
/// and impossible to notice, because a config that parses but names the
/// wrong folder syncs nothing and reports success.
///
/// With more than one account, each gets its own store, its own channels
/// and its own subtree; the single group syncs all of them, so
/// `lisa mail sync` stays one command.
pub fn render_mbsyncrc(accounts: &[Account], paths: &Paths, credential: &Credential) -> String {
    let mut out = String::new();
    out.push_str(MARKER);
    out.push_str("\n#\n# Run it with:  lisa mail sync\n\n");

    let multi = accounts.len() > 1;
    let mut channels = Vec::new();

    for account in accounts {
        let id = if multi {
            slug(&account.identity)
        } else {
            "lisa".to_string()
        };
        let root = account_root(&paths.maildir, &account.identity, multi);

        out.push_str(&format!("IMAPAccount {id}\n"));
        out.push_str(&format!("Host {}\n", account.imap_host));
        out.push_str(&format!("User {}\n", account.imap_user));

        match credential {
            Credential::OnlineAccount => {
                // A token, not a password: it expires in about an hour,
                // so it is fetched per run rather than written here.
                // `--account` names WHICH account to ask for, because
                // with several connected the helper cannot guess.
                out.push_str(&format!(
                    "PassCmd {}\n",
                    quote(&format!("lisa mail token --account {}", account.id))
                ));
                out.push_str("AuthMechs XOAUTH2\n");
            }
            Credential::AppPassword { file } => {
                out.push_str(&format!(
                    "PassCmd {}\n",
                    quote(&format!("cat {}", file.display()))
                ));
                out.push_str("AuthMechs LOGIN\n");
            }
        }

        if account.imap_ssl {
            out.push_str("TLSType IMAPS\n");
        } else {
            out.push_str("TLSType STARTTLS\n");
        }
        out.push_str("CertificateFile /etc/ssl/certs/ca-certificates.crt\n\n");

        out.push_str(&format!("IMAPStore {id}-remote\nAccount {id}\n\n"));
        out.push_str(&format!("MaildirStore {id}-local\n"));
        out.push_str(&format!("Path {}/\n", root.display()));
        out.push_str(&format!("Inbox {}/INBOX\n", root.display()));
        // Verbatim: folder names on disk are the names the Mail app
        // shows, so a folder called Archive is a directory called
        // Archive.
        out.push_str("SubFolders Verbatim\n\n");

        let folders = if is_gmail(&account.imap_host) {
            GMAIL_FOLDERS
        } else {
            GENERIC_FOLDERS
        };
        for (remote, local) in folders {
            let channel = format!("{id}-{}", local.to_ascii_lowercase());
            out.push_str(&format!("Channel {channel}\n"));
            out.push_str(&format!("Far :{id}-remote:{}\n", quote(remote)));
            out.push_str(&format!("Near :{id}-local:{}\n", quote(local)));
            // Create Near only: local folders appear as needed, and
            // nothing this machine does creates a folder in somebody
            // else's account.
            out.push_str("Create Near\n");
            // Neither side ever expunges, and neither side removes a
            // folder because the other lost it. Together these mean a
            // bug here costs flags, never messages.
            out.push_str("Expunge None\n");
            out.push_str("Remove None\n");
            out.push_str("SyncState *\n\n");
            channels.push(channel);
        }
    }

    out.push_str("Group lisa\n");
    for name in &channels {
        out.push_str(&format!("Channel {name}\n"));
    }
    out.push('\n');
    out
}

/// The sending half, as text.
///
/// msmtp rather than a client of our own: same reasoning as mbsync for
/// receiving. It implements XOAUTH2 natively instead of through Cyrus
/// SASL, so this needs no plugin — `passwordeval` runs the same token
/// helper mbsync uses.
///
/// One account block each plus a default, so `msmtp -a <slug>` picks the
/// identity and a bare `msmtp` still works.
pub fn render_msmtprc(accounts: &[Account], credential: &Credential) -> String {
    let mut out = String::new();
    out.push_str(MARKER);
    out.push_str("\n#\n# Sending half. Receiving is mbsyncrc, next to this file.\n\n");
    out.push_str("defaults\ntls on\ntls_trust_file /etc/ssl/certs/ca-certificates.crt\n");
    // A log is how a person finds out why a message did not leave. Under
    // the user's own state directory, never /var: mail is theirs.
    out.push_str("logfile ~/.local/state/lisa/msmtp.log\n\n");

    for account in accounts {
        let id = slug(&account.identity);
        // Gmail's submission host is smtp.<domain> where IMAP is
        // imap.<domain>; deriving it beats hardcoding one provider, and
        // GOA reports it directly for accounts that have it.
        let host = account
            .smtp_host
            .clone()
            .unwrap_or_else(|| account.imap_host.replacen("imap.", "smtp.", 1));
        out.push_str(&format!("account {id}\n"));
        out.push_str(&format!("host {host}\n"));
        out.push_str("port 587\n");
        out.push_str("tls_starttls on\n");
        out.push_str(&format!("from {}\n", account.identity));
        out.push_str(&format!("user {}\n", account.imap_user));
        match credential {
            Credential::OnlineAccount => {
                out.push_str("auth xoauth2\n");
                out.push_str(&format!(
                    "passwordeval \"lisa mail token --account {}\"\n",
                    account.id
                ));
            }
            Credential::AppPassword { file } => {
                out.push_str("auth on\n");
                out.push_str(&format!("passwordeval \"cat {}\"\n", file.display()));
            }
        }
        out.push('\n');
    }
    if let Some(first) = accounts.first() {
        out.push_str(&format!("account default : {}\n", slug(&first.identity)));
    }
    out
}

/// Refuse to overwrite a config we did not write.
pub fn may_write(existing: Option<&str>) -> bool {
    match existing {
        None => true,
        Some(text) => text.contains(MARKER),
    }
}

