    fn second() -> Account {
        Account {
            id: "account_1785447543_1".into(),
            identity: "other@gmail.test".into(),
            imap_host: "imap.gmail.com".into(),
            imap_user: "other@gmail.test".into(),
            imap_ssl: true,
            smtp_host: Some("smtp.gmail.com".into()),
        }
    }

    #[test]
    fn two_accounts_never_share_a_maildir() {
        // The failure this prevents is unrecoverable by hand: two
        // mailboxes syncing into one folder, with no way afterwards to
        // tell which message came from which account.
        let text = render_mbsyncrc(&[account(), second()], &paths(), &Credential::OnlineAccount);
        assert!(
            text.contains("Path /home/lisa/Mail/someone_at_example.test/"),
            "{text}"
        );
        assert!(
            text.contains("Path /home/lisa/Mail/other_at_gmail.test/"),
            "{text}"
        );
        // …and each fetches its own credential.
        assert!(text.contains("--account account_1785335038_0"), "{text}");
        assert!(text.contains("--account account_1785447543_1"), "{text}");
    }

    #[test]
    fn one_account_keeps_the_flat_layout_it_already_has() {
        // A single account must not be moved into a subdirectory: mail
        // is already synced there, and silently relocating somebody's
        // Maildir is not a migration, it is a disappearance.
        let text = render_mbsyncrc(&[account()], &paths(), &Credential::OnlineAccount);
        assert!(text.contains("Path /home/lisa/Mail/\n"), "{text}");
        assert!(!text.contains("someone_at_example.test"), "{text}");
        assert_eq!(
            account_root(Path::new("/m"), "a@b.test", false),
            PathBuf::from("/m")
        );
        assert_eq!(
            account_root(Path::new("/m"), "a@b.test", true),
            PathBuf::from("/m/a_at_b.test")
        );
    }

    #[test]
    fn every_channel_name_is_unique_across_accounts() {
        // mbsync channels share one namespace. Two accounts both naming
        // a channel `inbox` is a config that parses and syncs one
        // mailbox twice.
        let text = render_mbsyncrc(&[account(), second()], &paths(), &Credential::OnlineAccount);
        let names: Vec<&str> = text
            .lines()
            .filter_map(|l| l.strip_prefix("Channel "))
            .collect();
        let unique: std::collections::HashSet<&&str> = names.iter().collect();
        // Each channel is declared once and listed once in the group.
        assert_eq!(names.len(), unique.len() * 2, "{names:?}");
        assert!(
            names
                .iter()
                .any(|n| n.starts_with("someone_at_example.test-")),
            "{names:?}"
        );
    }

    #[test]
    fn an_address_becomes_a_name_a_person_can_recognise() {
        // The Maildir is a directory somebody will open in a file
        // manager one day.
        assert_eq!(slug("you@example.com"), "you_at_example.com");
        assert_eq!(slug("Odd Name+tag@x.test"), "Odd_Name_tag_at_x.test");
        assert_eq!(slug("../../etc/passwd"), ".._.._etc_passwd");
        assert_eq!(slug(""), "account");
        // No separator survives, so a slug can never climb out of the
        // Maildir root.
        for s in ["a/b@c", "a\\b@c", "..", "a\0b"] {
            let out = slug(s);
            assert!(
                !out.contains('/') && !out.contains('\\') && out != "..",
                "{s} -> {out}"
            );
        }
    }

    #[test]
    fn sending_uses_the_same_token_helper_and_never_stores_a_credential() {
        let text = render_msmtprc(&[account()], &Credential::OnlineAccount);
        assert!(text.contains("auth xoauth2"), "{text}");
        assert!(
            text.contains(r#"passwordeval "lisa mail token --account account_1785335038_0""#),
            "{text}"
        );
        // GOA reports SmtpAuthLogin=false and SmtpAuthPlain=false for
        // the connected Google account: XOAUTH2 is the only mechanism
        // that would work, so offering another would just fail later.
        assert!(!text.contains("auth on"), "{text}");
        assert!(text.contains("host smtp.gmail.com"), "{text}");
    }

    #[test]
    fn a_submission_host_is_derived_when_the_account_does_not_report_one() {
        // Not every provider tells us. Deriving smtp.<domain> from
        // imap.<domain> beats hardcoding one provider's hostnames.
        let mut a = account();
        a.smtp_host = None;
        a.imap_host = "imap.fastmail.com".into();
        let text = render_msmtprc(std::slice::from_ref(&a), &Credential::OnlineAccount);
        assert!(text.contains("host smtp.fastmail.com"), "{text}");
    }

    #[test]
    fn each_account_can_send_as_itself() {
        // Sending from the wrong address is the mail equivalent of
        // syncing two mailboxes into one folder: recoverable, but only
        // after somebody has already read it.
        let text = render_msmtprc(&[account(), second()], &Credential::OnlineAccount);
        assert!(text.contains("from someone@example.test"), "{text}");
        assert!(text.contains("from other@gmail.test"), "{text}");
        assert!(text.contains("--account account_1785335038_0"), "{text}");
        assert!(text.contains("--account account_1785447543_1"), "{text}");
        // A bare `msmtp` has to pick something, and picking silently is
        // worse than picking predictably.
        assert!(
            text.contains("account default : someone_at_example.test"),
            "{text}"
        );
    }

    #[test]
    fn a_hand_written_config_is_never_overwritten() {
        // ~/.mbsyncrc is somebody's own file. This one is ours, at our
        // own path, and even there we check before replacing.
        assert!(may_write(None));
        assert!(may_write(Some(&format!("{MARKER}\nIMAPAccount lisa\n"))));
        assert!(!may_write(Some(
            "IMAPAccount mine\nHost imap.example.test\n"
        )));
    }

    #[test]
    fn the_maildir_is_where_the_app_looks() {
        let p = Paths::new(Path::new("/home/lisa"), None);
        assert_eq!(p.maildir, PathBuf::from("/home/lisa/Mail"));
        assert_eq!(p.config, PathBuf::from("/home/lisa/.config/lisa/mbsyncrc"));
        // …and an override is honoured, because the app has one too.
        let p = Paths::new(Path::new("/home/lisa"), Some(PathBuf::from("/srv/mail")));
        assert_eq!(p.maildir, PathBuf::from("/srv/mail"));
    }
